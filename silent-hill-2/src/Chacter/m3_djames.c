static void DemoJamesCheckModelParts(SubCharacter* this) {
    int rhand;  
    int lhand;
    int light;
    
    if ((sh2jms.player->status & (1 << SCP_STATUS_BIT_15)) || !(GET_ITEM_FLAG(15))) {
        light = 0;
    } else {
        light = 21;
    }
    
    if (this->kind == HHH_JMS_CHARA_KIND) {       
        rhand = lhand = 0;
    } else {
        lhand = 0;
        switch (sh2jms.weapon) {
            case 0:
                rhand = 3;
                break;
            case 1:
                rhand = 7;
                break;
            case 2:
            case 3:
                rhand = 8;
                break;
            case 4:
                rhand = 11;
                break;
            case 5:
                rhand = 10;
                break;
            case 6:
                rhand = 9;
                break;
            case 8:
                rhand = 12;
                break;
            case 7:
                rhand = 13;
                break;
        }
    }
    
    
    sh2gfw_Set_JMSequip(this, lhand, rhand, light);
}

