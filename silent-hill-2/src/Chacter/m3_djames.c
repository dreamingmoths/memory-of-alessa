int shCharacterHumanDJAMESAnimeSet(SubCharacter* scp, int anime_id) {
    short id;
    AnimeInfo* aip;

    id = shCharacterGetModelID(scp);
    
    if ((id == HHH_JMS_CHARA_KIND) || (id == HHL_JMS_CHARA_KIND)) {
        
        
        aip = (AnimeInfo*) &djames_anim[(anime_id - DJAMES_DRAMA_ANIME_ID_START)];     
        shCharacterAnimeSet(scp,
                            0,
                            2,
                            aip,
                            djames_anime_adr_list[anime_id - DJAMES_DRAMA_ANIME_ID_START] + (int) shCharacterGetAnimeAdrForDrama(scp, anime_id - DJAMES_DRAMA_ANIME_ID_START));        
        
        
        
        
        
        
        
        
        
        
        shCharacterClusterAnimeSet(scp,
                                   djames_clani_adr_list[anime_id - DJAMES_DRAMA_ANIME_ID_START] + (int) shCharacterGetClusterAnimeAdr(scp));
        
        
        
        
        
        return 0;
    }
    return -1;

}

static int HumanRDJMSInit(SubCharacter* scp) {
    SCAnimeTypeSwitch(scp, 0);
    
    scp->model_type = 1;
    
    
    switch (sh2jms.room_name_now) {
        case 1:
            mirror_mode_0x003C7EC0 = 0;
            wall_pos_0x003C7EC8 = -20000.0f;
            break;
        case 36:
            mirror_mode_0x003C7EC0 = 2;
            wall_pos_0x003C7EC8 = -99995.0f;
            break;
    }
    return 0;
}

static void HumanRDJMSFunction(SubCharacter* this) {
    SubCharacter* scp;

    switch (this->step) {
        case 0:
            HumanRDJMSInit(this);
            this->step++;
            break;
        
        case 1:
            scp = shCharacterGetSubCharacter((this->kind - MIRROR_MODE_CHARA_KIND_FLAG), -1);
            if (scp != NULL) {
                
                
                switch (mirror_mode_0x003C7EC0) {
                    
                    case 0:                        
                        this->pos.x = wall_pos_0x003C7EC8 + (wall_pos_0x003C7EC8 - scp->pos.x);
                        this->pos.y = scp->pos.y;
                        this->pos.z = scp->pos.z;
                        this->rot.y = -scp->rot.y;
                        break;
                    
                    case 1:
                        this->pos.x = scp->pos.x;
                        
                        
                        
                        
                        
                        this->pos.y = wall_pos_0x003C7EC8 + (wall_pos_0x003C7EC8 - scp->pos.y);
                        
                        this->pos.z = scp->pos.z;
                        this->rot.y = scp->rot.y;
                        this->rot.z = PI;
                        break;
                    
                    case 2:
                        this->pos.x = scp->pos.x;
                        this->pos.y = scp->pos.y;
                        this->pos.z = wall_pos_0x003C7EC8 + (wall_pos_0x003C7EC8 - scp->pos.z);
                        if (scp->rot.y >= 0.0f) {
                            this->rot.y = PI - scp->rot.y;
                        } else
                            this->rot.y = -PI - scp->rot.y;
                        
                }
            } 
            break;
    }

}

void shCharacterSetHumanRDJMSLow(SubCharacter* scp) {
    shCharacterSetFunction(scp, HumanRDJMSFunction);
}
