static void HumanDJMSFunction(SubCharacter* this) {
    AnimeInfo* aip;

    
    
    switch (this->step) {
        case 0:
            
            
            
            HumanDJMSInit(this);
            aip = (AnimeInfo*) &djames_anim[1];
            
            shCharacterAnimeSet(this, 0, 0, aip, (int) shCharacterGetAnimeAdrForDrama(this, 1));
            
            
            
            this->step++;
            break;
        
        
        case 1:
            DemoJamesCheckModelParts(this);
            
            
            DemoPlayerSetHeight(this);
            break;
    }


}

void DemoPlayerSetHeight(SubCharacter* this) {
    sceVu0FVECTOR sp; sceVu0FVECTOR ep;  
    CL_VHIT_RESULT floor;
    
    shVectorCopy(sp, &this->pos);
    shVectorCopy(ep, sp);
    sp[1] -= 250.0f;
    ep[1] += 1500.0f;
    clCheckHitEyesOnlyFloor(&floor, (int) this, sp, ep);
    
    if (floor.kind == 1) {    
        this->grnd_height = floor.hobj.wall.cp[1];
        this->grnd_normal = floor.hobj.wall.nl;        
    } else {
        this->grnd_height = 0.0f;
        this->grnd_normal[0] = this->grnd_normal[1] = this->grnd_normal[2] = this->grnd_normal[3] = 0.0f;
    }



}

